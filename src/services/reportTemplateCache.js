import apiClient from "./apiClient";

// Reads the static texts of a backend Stimulsoft report template
// (served by the backend at /Reports/<name>.mrt), so report labels match the
// backend report exactly.
const templateRequests = new Map();

const decodeXmlText = (value) =>
  value
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, "&");

const extractTemplateTexts = (xml) =>
  [...String(xml).matchAll(/<Text>([\s\S]*?)<\/Text>/g)]
    .map((match) => decodeXmlText(match[1]).trim())
    .filter(Boolean);

export const loadReportTemplateTexts = (reportName) => {
  if (!templateRequests.has(reportName)) {
    const request = apiClient
      .get(`/Reports/${reportName}.mrt`, { responseType: "text" })
      .then((response) => extractTemplateTexts(response.data))
      .catch((error) => {
        templateRequests.delete(reportName);
        throw error;
      });
    templateRequests.set(reportName, request);
  }
  return templateRequests.get(reportName);
};

// "Label : {root.Field}" lines, e.g. "Generated By : {root.GeneratedBy}"; column
// headers such as "Total Duration (Hours) For {root.UserName}" are left out.
export const getRootTemplateLines = (texts) =>
  texts.filter((text) => /^[^{}]+ : \{root\.\w+\}$/.test(text));

export const getTemplateLineFields = (text) =>
  [...text.matchAll(/\{root\.(\w+)\}/g)].map((match) => match[1]);

// Replaces each {root.Field} with the matching report value.
export const fillTemplateLine = (text, getValue) =>
  text.replace(/\{root\.(\w+)\}/g, (placeholder, field) => {
    const value = getValue(field);
    return value === null || value === undefined ? "" : String(value);
  });
